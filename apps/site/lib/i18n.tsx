const I18nContext = createContext<I18nContextValue | null>(null);
const languageStorageKey = 'pe-site-language';

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    const saved = window.localStorage.getItem(languageStorageKey);
    if (saved === 'en' || saved === 'fr') {
      setLangState(saved);
      document.documentElement.lang = saved;
    }
  }, []);

  const setLang = (next: Lang) => {
    setLangState(next);
    window.localStorage.setItem(languageStorageKey, next);
    document.documentElement.lang = next;
  };

  const value = useMemo(() => ({ lang, setLang, t: dictionaries[lang] as Dict, timezone: 'UTC' }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within LanguageProvider');
  return context;
}

export function LanguageSwitcher({ value, onChange }: { value?: Lang; onChange?: (lang: Lang) => void } = {}) {
  const { lang, setLang, t } = useI18n();
  const selectedLang = value ?? lang;
  const changeLanguage = onChange ?? setLang;
  return (
    <div className="site-language-toggle flex rounded-full border border-white/10 bg-white/5 p-1" aria-label={t.common.language}>
      {(['en', 'fr'] as const).map((item) => (
        <button
          key={item}
          type="button"
          onClick={() => changeLanguage(item)}
          className={`rounded-full px-3 py-1 text-xs font-bold uppercase ${selectedLang === item ? 'bg-accent text-background' : 'text-white/70'}`}
          aria-pressed={selectedLang === item}
        >
          {item}
        </button>
      ))}
    </div>
  );
}

export function statusLabel(t: Dict, value?: string | null) {
  if (!value) return '';
  return t.status[value as keyof typeof t.status] ?? value;
}

export function auditLabel(t: Dict, value?: string | null) {
  if (!value) return t.audit.fallback;
  return t.audit[value as keyof typeof t.audit] ?? value;
}
